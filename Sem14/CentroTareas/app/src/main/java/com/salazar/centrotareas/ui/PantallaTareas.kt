import com.salazar.centrotareas.viewmodel.TareasViewModel

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PantallaTareas(vm: TareasViewModel) {
    val mensaje by vm.mensaje.collectAsState()
    val primos by vm.primos.collectAsState()
    val carga by vm.carga.collectAsState()

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("CentroTareas") },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.primary,
                    titleContentColor = MaterialTheme.colorScheme.onPrimary
                )
            )
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .verticalScroll(rememberScrollState())
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {
            // Prueba de vida: si deja de sumar, la pantalla está congelada
            var toques by rememberSaveable { mutableIntStateOf(0) }
            Button(
                onClick = { toques++ },
                modifier = Modifier.fillMaxWidth()
            ) { Text("Tócame: $toques") }

            TarjetaTarea("Tarea con progreso") {
                Button(onClick = { vm.tareaLargaMala() }) { Text("Tarea larga (MAL)") }
                Text(mensaje)
            }
            TarjetaTarea("Contar números primos") {
                ResultadoPrimos(primos)
            }
            TarjetaTarea("Dos cargas") {
                ResultadoCarga(carga, onReintentar = { })
            }
        }
    }
}

@Composable
private fun TarjetaTarea(titulo: String, contenido: @Composable () -> Unit) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant)
    ) {
        Column(
            modifier = Modifier.padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            Text(
                titulo,
                style = MaterialTheme.typography.titleMedium,
                color = MaterialTheme.colorScheme.primary
            )
            contenido()
        }
    }
}
